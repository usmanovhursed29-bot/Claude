// Задание для модели и формат ответа. Системный промт неизменен между запросами: он кэшируется.

export const MODEL = "claude-opus-5-5";

export const SYSTEM = `Ты помогаешь автору образовательного канала о Коране (YouTube, Instagram, TikTok) находить в аятах мысли, которые полезно и интересно узнать современному человеку, и честно отделять надёжное от спорного.

Тебе дают отрывок: арабский текст и русский перевод смыслов Э. Кулиева. Найди в нём от 0 до 3 идей для коротких роликов. Идея — это одна ясная мысль из отрывка и то, как её применить в жизни сегодня. Если в отрывке нет сильной идеи, верни пустой список: это нормальный ответ.

Типы идей:
- "жизненный урок" — практический вывод из смысла аята: отношения, деньги, благодарность, терпение, честность, страх, надежда;
- "наука" — аят касается явления природы, о котором есть установленные научные факты;
- "язык" — интересная деталь арабского слова или построения фразы;
- "история" — урок из истории пророков и народов, связанный с сегодняшним днём.

Жёсткие правила:
1. Опирайся только на данный текст. Не цитируй другие аяты по памяти, не приводи хадисы, не называй номера хадисов.
2. Не выдумывай толкования. В поле "classical_view" пиши только то, что классические тафсиры (ат-Табари, Ибн Касир, аль-Куртуби, ас-Саади) общеизвестно говорят об этом аяте, и честно указывай уверенность. Если не уверен, пиши "не уверен, проверить по тафсиру".
3. Не утверждай, что Коран "доказывает" научную теорию. Пиши, что сказано в аяте, что известно науке, и насколько сильна связь. Связь, которая держится на натяжке перевода, помечай "speculative".
4. Числа и подсчёты (сколько раз слово встречается и т.п.) не приводи: их считает отдельная программа. Если идея держится на числе, опиши, что нужно посчитать, в поле "count_to_verify".
5. Медицину, питание и психологию не связывай с аятом прямыми обещаниями ("пей витамин D — станешь благодарнее"). Можно говорить о научно подтверждённых эффектах благодарности, сна, поста и т.п., только с пометкой, что это нужно подтвердить источником.
6. Уважительный тон. Никаких фетв и юридических решений. Всё спорное с точки зрения вероубеждения отмечай needs_scholar_review = true.
7. Пиши по-русски, просто и живо, как для зрителя 16–35 лет.`;

export const userPrompt = (p) =>
  [
    `Сура ${p.s} «${p.surahRu}» (${p.surahAr}), аяты ${p.from}–${p.to}.`,
    "",
    ...p.verses.map((v) => `[${v.s}:${v.a}] ${v.ar}\n${v.ru}`),
  ].join("\n");

const str = { type: "string" };
export const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["ideas"],
  properties: {
    ideas: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: [
          "title", "ayahs", "type", "hook", "text_says", "classical_view", "modern_application",
          "science", "count_to_verify", "video_potential", "risk", "risk_reason", "needs_scholar_review",
        ],
        properties: {
          title: { ...str, description: "Название ролика, до 60 символов" },
          ayahs: { ...str, description: "Номера аятов, например 16:68-69" },
          type: { type: "string", enum: ["жизненный урок", "наука", "язык", "история"] },
          hook: { ...str, description: "Первая фраза ролика, цепляющая, но честная" },
          text_says: { ...str, description: "Что прямо сказано в аяте по переводу смыслов" },
          classical_view: { ...str, description: "Что общеизвестно пишут классические тафсиры, с уверенностью" },
          modern_application: { ...str, description: "Как применить это сегодня, конкретно" },
          science: {
            type: "object",
            additionalProperties: false,
            required: ["claim", "status", "what_to_check"],
            properties: {
              claim: { ...str, description: "Научный факт по теме, или пустая строка" },
              status: { type: "string", enum: ["none", "established", "debated", "speculative"] },
              what_to_check: { ...str, description: "Какой источник нужен для проверки" },
            },
          },
          count_to_verify: { ...str, description: "Что посчитать программой, или пустая строка" },
          video_potential: { type: "integer", enum: [1, 2, 3, 4, 5] },
          risk: { type: "string", enum: ["low", "medium", "high"] },
          risk_reason: str,
          needs_scholar_review: { type: "boolean" },
        },
      },
    },
  },
};

// Общие параметры запроса. Системный промт кэшируется (одинаковый префикс у всех 603 запросов).
export const requestParams = (p, { effort = "medium" } = {}) => ({
  model: MODEL,
  max_tokens: 16000,
  system: [{ type: "text", text: SYSTEM, cache_control: { type: "ephemeral" } }],
  output_config: { effort, format: { type: "json_schema", schema: SCHEMA } },
  messages: [{ role: "user", content: userPrompt(p) }],
});
