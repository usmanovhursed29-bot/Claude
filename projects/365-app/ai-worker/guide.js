// Отправить гайд и закрепить первое сообщение.
export async function sendGuide(tg, chatId) {
  let first = null;
  for (const text of GUIDE) {
    const r = await tg("sendMessage", { chat_id: chatId, text, disable_web_page_preview: true });
    if (!first) first = r?.result?.message_id ?? r?.message_id ?? null;
  }
  if (first) await tg("pinChatMessage", { chat_id: chatId, message_id: first, disable_notification: true }).catch(() => {});
}
