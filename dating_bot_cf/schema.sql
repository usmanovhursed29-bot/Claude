CREATE TABLE IF NOT EXISTS users (
  user_id INTEGER PRIMARY KEY, username TEXT, name TEXT NOT NULL, age INTEGER NOT NULL,
  gender TEXT NOT NULL, looking TEXT NOT NULL, city TEXT NOT NULL, about TEXT NOT NULL DEFAULT '',
  photo_id TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, banned INTEGER NOT NULL DEFAULT 0,
  premium_until INTEGER NOT NULL DEFAULT 0, f_city_only INTEGER NOT NULL DEFAULT 0,
  f_age_min INTEGER NOT NULL DEFAULT 0, f_age_max INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS views (
  from_id INTEGER NOT NULL, to_id INTEGER NOT NULL, action TEXT NOT NULL, created INTEGER NOT NULL,
  PRIMARY KEY (from_id, to_id)
);
CREATE TABLE IF NOT EXISTS likes (
  from_id INTEGER NOT NULL, to_id INTEGER NOT NULL, message TEXT, responded INTEGER NOT NULL DEFAULT 0,
  created INTEGER NOT NULL, PRIMARY KEY (from_id, to_id)
);
CREATE TABLE IF NOT EXISTS reports (from_id INTEGER NOT NULL, to_id INTEGER NOT NULL, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS payments (
  user_id INTEGER NOT NULL, charge_id TEXT NOT NULL, stars INTEGER NOT NULL, days INTEGER NOT NULL, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS fsm (user_id INTEGER PRIMARY KEY, state TEXT, data TEXT NOT NULL DEFAULT '{}');
CREATE INDEX IF NOT EXISTS idx_likes_to ON likes (to_id, responded);
CREATE INDEX IF NOT EXISTS idx_users_feed ON users (active, banned, gender, age);
